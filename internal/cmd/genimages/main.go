// Command genimages renders pinned runtime image constants without network I/O.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"os"
	"regexp"
	"sort"
)

func generate(input []byte) ([]byte, error) {
	var images map[string]string
	dec := json.NewDecoder(bytes.NewReader(input))
	if err := dec.Decode(&images); err != nil {
		return nil, err
	}
	if err := dec.Decode(new(any)); err != io.EOF {
		return nil, fmt.Errorf("expected one JSON object")
	}
	patterns := map[string]string{
		"DefaultEmulatorImage": `^gcr\.io/cloud-spanner-emulator/emulator:[0-9]+\.[0-9]+\.[0-9]+$`,
		"DefaultOmniImage":     `^us-docker\.pkg\.dev/spanner-omni/images/spanner-omni:[0-9]{4}\.r[0-9]+(-lts)?(\.[0-9]+)?$`,
		"LatestLTSOmniImage":   `^us-docker\.pkg\.dev/spanner-omni/images/spanner-omni:[0-9]{4}\.r[0-9]+-lts(\.[0-9]+)?$`,
	}
	if len(images) != len(patterns) {
		return nil, fmt.Errorf("expected exactly three image references")
	}
	names := make([]string, 0, len(patterns))
	for name, pattern := range patterns {
		if !regexp.MustCompile(pattern).MatchString(images[name]) {
			return nil, fmt.Errorf("invalid pinned image for %s", name)
		}
		names = append(names, name)
	}
	sort.Strings(names)
	comments := map[string]string{
		"DefaultEmulatorImage": "DefaultEmulatorImage is the latest known non-prerelease emulator image\n// selected by this spanemuboost version. It is not resolved at runtime.",
		"DefaultOmniImage":     "DefaultOmniImage is the latest known non-prerelease Omni Developer image\n// selected by this spanemuboost version. It is not resolved at runtime.\n// Omni integration remains experimental.",
		"LatestLTSOmniImage":   "LatestLTSOmniImage is the latest known Omni Developer LTS image selected\n// by this spanemuboost version. Use WithContainerImage(LatestLTSOmniImage)\n// to select it instead of DefaultOmniImage. It is not resolved at runtime.",
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage spanemuboost\n\n")
	for _, name := range names {
		fmt.Fprintf(&out, "// %s\nconst %s = %q\n\n", comments[name], name, images[name])
	}
	return format.Source(out.Bytes())
}
func main() {
	input, err := os.ReadFile("runtime-images.json")
	if err == nil {
		var out []byte
		out, err = generate(input)
		if err == nil {
			err = os.WriteFile("images_generated.go", out, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
